# -*- coding: utf-8 -*-
"""
最小版：按年复利计算到期本息
已知：本金 10000 元，年利率 5%，存 3 年
复利公式：本息 = 本金 * (1 + 年利率) ** 年限
检查点：运行结果应为 11576.25
"""

P = 10000          # 本金（元）
r = 0.05           # 年利率（5%）
t = 3              # 存款年限（年）

amount = P * (1 + r) ** t

print("====== 最小版：按年复利 ======")
print(f"本金：{P} 元")
print(f"年利率：{r:.0%}")
print(f"年限：{t} 年")
print(f"到期本息：{amount:.2f} 元")
