"""
独立研究任务 2：把"按年复利（n=1）"改成"按月复利（n=12）"
一般复利公式：本息 = 本金 * (1 + 年利率 / n) ** (n * 年限)
  n = 1  ：每年计息 1 次（按年复利）
  n = 12 ：每月计息 1 次，月利率 = 年利率 / 12，总期数 = 12 * 年限
"""

P = 10000.0        # 本金（元）
r = 0.05           # 年利率


def compound(P, r, t, n=1):
    """每年计息 n 次的复利本息。"""
    return P * (1 + r / n) ** (n * t)


print("====== 年复利与月复利对比（本金 10000 元，年利率 5%）======")
print(f"{'年限':>4}{'年复利 n=1(元)':>18}{'月复利 n=12(元)':>18}{'月复利多(元)':>16}")
print("-" * 56)

for t in (3, 10, 30):
    a = compound(P, r, t, n=1)
    m = compound(P, r, t, n=12)
    print(f"{t:>4}{a:>18,.2f}{m:>18,.2f}{m - a:>16,.2f}")

print()
print("结论：")
print("1. 月复利每期利率为 5%/12≈0.4167%，一年计息 12 次，利息更早进入本金再生利息，")
print("   所以同一时间下月复利本息始终略高于年复利。")
print("2. 3 年差距很小（约 38.47 元）；时间拉长到 30 年，差距被指数效应放大到上千元。")
print("3. 计息频率越高，实际年化收益率（实际利率）越高，但边际增量越来越小。")
